package com.github.eladrimonos.jasprintellij.startup

import com.github.eladrimonos.jasprintellij.JasprBundle
import com.github.eladrimonos.jasprintellij.actions.JasprUpdateCliAction
import com.github.eladrimonos.jasprintellij.execution.runconfig.JasprRunConfigurationSetup
import com.github.eladrimonos.jasprintellij.icons.JasprIcons
import com.github.eladrimonos.jasprintellij.module.JasprModuleConfigurator
import com.github.eladrimonos.jasprintellij.services.JasprCliMissingException
import com.github.eladrimonos.jasprintellij.services.JasprTooling
import com.github.eladrimonos.jasprintellij.services.JasprToolingDaemonService
import com.github.eladrimonos.jasprintellij.services.MelosScriptInjector
import com.github.eladrimonos.jasprintellij.services.MelosWorkspaceDetector
import com.intellij.notification.NotificationAction
import com.intellij.notification.NotificationGroupManager
import com.intellij.notification.NotificationType
import com.intellij.openapi.application.ApplicationManager
import com.intellij.openapi.project.Project
import com.intellij.openapi.startup.ProjectActivity
import java.io.File
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

class JasprProjectActivity : ProjectActivity {
    override suspend fun execute(project: Project) {
        if (!JasprTooling.isJasprProject(project)) return
        val basePath = project.basePath ?: return
        val projectDir = File(basePath)

        JasprRunConfigurationSetup.addIfNeeded(project, projectDir)
        JasprModuleConfigurator.ensureConfigured(project)

        withContext(Dispatchers.IO) {
            val workspaceInfo = MelosWorkspaceDetector.detect(projectDir)
            if (workspaceInfo != null) {
                // `stdio: inherit` (Melos >= 7.8.0) lets daemon.shutdown and hot reload reach
                // the daemon; read the version here, off the EDT.
                val melosSupportsInheritedStdio = JasprDartSdkResolver.getConfiguredDartSdkHomePath(project)
                    ?.let { JasprTooling().readMelosVersion(it) }
                    .let { JasprTooling().isVersionAtLeast(it, MelosScriptInjector.INHERITED_STDIO_MELOS_VERSION) }
                withContext(Dispatchers.Main) {
                    // Upgrade scripts generated by older plugin versions (see MelosScriptInjector).
                    MelosScriptInjector.migrateManagedBlock(
                        workspaceInfo.melosConfigFile,
                        if (melosSupportsInheritedStdio) {
                            { name -> MelosWorkspaceDetector.resolveMemberPackageRelativeDir(workspaceInfo, name) }
                        } else null,
                    )
                    if (!JasprRunConfigurationSetup.isMelosInjectionDismissed(project)) {
                        JasprRunConfigurationSetup.notifyAndConfigureForMelos(
                            project, projectDir, workspaceInfo, melosSupportsInheritedStdio,
                        )
                    }
                }
            }

            val sdkPath = JasprDartSdkResolver.getConfiguredDartSdkHomePath(project) ?: return@withContext
            val tooling = JasprTooling()

            // preflightCheck already runs `jaspr --version`; the daemon service keeps it for the
            // run configurations and the per-file CLI version mismatch banner.
            try {
                val cliVersion = tooling.preflightCheck(sdkPath)
                project.getService(JasprToolingDaemonService::class.java)?.start(knownCliVersion = cliVersion)
            } catch (e: Exception) {
                if (e is JasprCliMissingException) {
                    withContext(Dispatchers.Main) {
                        NotificationGroupManager.getInstance()
                            .getNotificationGroup("JasprIntelliJ")
                            .createNotification(
                                JasprBundle.message("jaspr.notification.preflight.title"),
                                JasprBundle.message("jaspr.notification.preflight.content", e.localizedMessage?.substringBefore("\n") ?: JasprBundle.message("jaspr.unknown.error")),
                                NotificationType.ERROR
                            )
                            .setIcon(JasprIcons.JasprLogo)
                            .addAction(NotificationAction.create(JasprBundle.message("jaspr.notification.preflight.install")) { _, notification ->
                                JasprUpdateCliAction().runAction(project) {
                                    // Restart daemon after installation
                                    ApplicationManager.getApplication().executeOnPooledThread {
                                        project.getService(JasprToolingDaemonService::class.java)?.restart()
                                    }
                                }
                                notification.expire()
                            })
                            .notify(project)
                    }
                } else {
                    // Log other preflight errors
                    com.intellij.openapi.diagnostic.Logger.getInstance(JasprProjectActivity::class.java)
                        .warn("Jaspr preflight check failed: ${e.localizedMessage}")
                }
            }
        }
    }
}
