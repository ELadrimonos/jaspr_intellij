package com.github.eladrimonos.jasprintellij.services

import java.io.File
import java.nio.file.Files
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test

class JasprToolingVersionTest {

    private lateinit var tempDir: File
    private val tooling = JasprTooling()

    @Before
    fun setUp() {
        tempDir = Files.createTempDirectory("jaspr_tooling_version_test").toFile()
    }

    @After
    fun tearDown() {
        tempDir.deleteRecursively()
    }

    private fun lockfileWithJaspr(version: String): String = """
        |# Generated by pub
        |# See https://dart.dev/tools/pub/glossary#lockfile
        |packages:
        |  args:
        |    dependency: transitive
        |    description:
        |      name: args
        |      sha256: "abc"
        |      url: "https://pub.dev"
        |    source: hosted
        |    version: "2.5.0"
        |  jaspr:
        |    dependency: "direct main"
        |    description:
        |      name: jaspr
        |      sha256: "def"
        |      url: "https://pub.dev"
        |    source: hosted
        |    version: "$version"
        |sdks:
        |  dart: ">=3.5.0 <4.0.0"
        |""".trimMargin()

    @Test
    fun `reads the resolved jaspr version from pubspec lock in the same directory`() {
        File(tempDir, "pubspec.lock").writeText(lockfileWithJaspr("0.23.4"))

        assertEquals("0.23.4", tooling.readResolvedFrameworkVersion(tempDir))
    }

    @Test
    fun `finds the lockfile in a parent directory for a pub workspace member`() {
        File(tempDir, "pubspec.lock").writeText(lockfileWithJaspr("0.23.4"))
        val memberDir = File(tempDir, "packages/website").apply { mkdirs() }
        File(memberDir, "pubspec.yaml").writeText("name: website\nresolution: workspace\n")

        assertEquals("0.23.4", tooling.readResolvedFrameworkVersion(memberDir))
    }

    @Test
    fun `returns null when there is no lockfile`() {
        assertNull(tooling.readResolvedFrameworkVersion(tempDir))
    }

    @Test
    fun `returns null when the lockfile has no jaspr entry`() {
        File(tempDir, "pubspec.lock").writeText(
            """
            |packages:
            |  args:
            |    dependency: transitive
            |    source: hosted
            |    version: "2.5.0"
            |""".trimMargin()
        )

        assertNull(tooling.readResolvedFrameworkVersion(tempDir))
    }

    @Test
    fun `strips the pre-release suffix from the resolved version`() {
        File(tempDir, "pubspec.lock").writeText(lockfileWithJaspr("0.24.0-beta.0"))

        assertEquals("0.24.0", tooling.readResolvedFrameworkVersion(tempDir))
    }

    @Test
    fun `same minor with a different patch is not a mismatch`() {
        assertFalse(tooling.isVersionMismatch("0.23.5", "0.23.4"))
        assertFalse(tooling.isVersionMismatch("0.23.4", "0.23.0"))
    }

    @Test
    fun `different minor is a mismatch`() {
        assertTrue(tooling.isVersionMismatch("0.24.0", "0.23.4"))
    }

    @Test
    fun `same version is not a mismatch`() {
        assertFalse(tooling.isVersionMismatch("0.23.4", "0.23.4"))
    }
}
